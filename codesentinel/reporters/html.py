"""Standalone HTML report — a self-contained, shareable artifact (no external deps)."""
from __future__ import annotations

import html
from typing import List

from codesentinel.models import Finding, ScanResult

_SEV_COLOR = {
    "CRITICAL": "#b91c1c", "HIGH": "#c2410c", "MEDIUM": "#b45309",
    "LOW": "#0369a1", "INFO": "#475569",
}


def _badge(sev: str) -> str:
    color = _SEV_COLOR.get(sev.upper(), "#475569")
    return (f'<span style="background:{color};color:#fff;padding:2px 8px;'
            f'border-radius:4px;font-size:12px;font-weight:600">{html.escape(sev)}</span>')


def _finding_html(f: Finding) -> str:
    tag = html.escape(f.cwe or f.rule_id)
    loc = html.escape(f"{f.location.path}:{f.location.start_line}")
    parts = [
        '<div class="finding">',
        f'<div class="fhead">{_badge(f.severity)} <span class="tag">{tag}</span> '
        f'<span class="loc">{loc}</span> '
        f'<span class="conf">confidence {f.confidence:.2f}</span></div>',
        f'<div class="cat">{html.escape(f.category)} — {html.escape(f.message.splitlines()[0])}</div>',
    ]
    if f.location.snippet:
        parts.append(f'<pre class="code">{html.escape(f.location.snippet.strip())}</pre>')
    if f.fix:
        parts.append(f'<div class="fix"><b>Remediation:</b> {html.escape(f.fix)}</div>')
    if f.citation and f.citation.passage_id:
        parts.append(f'<div class="prov">Provenance: '
                     f'{html.escape(f.citation.doc)} :: {html.escape(f.citation.passage_id)}</div>')
    parts.append("</div>")
    return "\n".join(parts)


def render(result: ScanResult) -> str:
    s = result.summary()
    by = s["by_severity"]
    cards = "".join(
        f'<div class="card" style="border-top:3px solid {_SEV_COLOR[k]}">'
        f'<div class="num">{by[k]}</div><div class="lbl">{k.title()}</div></div>'
        for k in ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]
    )
    findings = "".join(_finding_html(f) for f in result.findings) or \
        '<p class="none">No findings.</p>'
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>CodeSentinel Report — {html.escape(result.target)}</title>
<style>
 body{{font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;
   margin:0;background:#f8fafc;color:#0f172a}}
 header{{background:#0f172a;color:#fff;padding:24px 32px}}
 header h1{{margin:0;font-size:22px}} header .meta{{opacity:.8;font-size:13px;margin-top:6px}}
 main{{max-width:980px;margin:0 auto;padding:24px 32px}}
 .cards{{display:flex;gap:12px;margin:0 0 24px}}
 .card{{flex:1;background:#fff;border:1px solid #e2e8f0;border-radius:8px;padding:16px;text-align:center}}
 .card .num{{font-size:28px;font-weight:700}} .card .lbl{{color:#64748b;font-size:13px}}
 .finding{{background:#fff;border:1px solid #e2e8f0;border-radius:8px;padding:16px;margin-bottom:14px}}
 .fhead{{display:flex;gap:10px;align-items:center;flex-wrap:wrap}}
 .tag{{font-family:ui-monospace,Menlo,monospace;font-weight:600}}
 .loc{{color:#475569;font-family:ui-monospace,Menlo,monospace;font-size:13px}}
 .conf{{margin-left:auto;color:#94a3b8;font-size:12px}}
 .cat{{margin:8px 0;font-weight:500}}
 pre.code{{background:#0f172a;color:#e2e8f0;padding:12px;border-radius:6px;overflow:auto;font-size:13px}}
 .fix{{background:#f0fdf4;border-left:3px solid #16a34a;padding:8px 12px;border-radius:4px;font-size:14px}}
 .prov{{color:#64748b;font-size:12px;margin-top:8px}}
 .none{{color:#16a34a;font-weight:600}}
 footer{{text-align:center;color:#94a3b8;font-size:12px;padding:24px}}
</style></head><body>
<header><h1>CodeSentinel Security Report</h1>
<div class="meta">Target: {html.escape(result.target)} &nbsp;·&nbsp; Version {html.escape(result.tool_version)}
 &nbsp;·&nbsp; {html.escape(result.edition)} edition &nbsp;·&nbsp;
 {s['total_findings']} finding(s) across {s['files_scanned']} file(s) &nbsp;·&nbsp;
 {result.duration_seconds:.2f}s</div></header>
<main>
<div class="cards">{cards}</div>
{findings}
</main>
<footer>Generated by CodeSentinel — every security finding is RAG-grounded and adversarially validated.</footer>
</body></html>"""
